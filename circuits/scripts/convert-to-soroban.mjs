// Convert snarkjs BLS12-381 vk/proof/public JSON into Soroban bls12_381 byte
// layout (hex), for the soroban-contract verifier + its correctness test.
//   G1 (96B): BE(X) || BE(Y)
//   G2 (192B): BE(X_c1) || BE(X_c0) || BE(Y_c1) || BE(Y_c0)   <- c1 BEFORE c0
//   Fr (32B): BE
// snarkjs stores Fp2 as [c0, c1], so we swap to c1,c0.
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

// Usage (from any directory):
//   node convert-to-soroban.mjs            -> claim circuit (default, unchanged)
//   node convert-to-soroban.mjs joinsplit  -> shielded-pool join-split
//   node convert-to-soroban.mjs --out <path> [circuit]
//     -> writes only the converted JSON to <path>; never touches any
//        contract fixture (*.rs), regardless of the pinned-fixture guard
//        below. For producing a one-off conversion (e.g. to regenerate a
//        benchmark-only Rust fixture by hand) without the side effect of
//        overwriting a tracked fixture.
//   node convert-to-soroban.mjs --rs <path.rs> [circuit]
//     -> writes the Rust constants to <path.rs> instead of the fixture the
//        circuit argument would imply, so a benchmark-only fixture such as
//        contracts/verifier/src/claim_fixture_7in.rs can be re-pinned without
//        hand-copying hex. If <path.rs> exists, everything above its first
//        `pub const` is kept verbatim: that prose records which proof the file
//        freezes and why, which a generator cannot reconstruct. Combines with
//        --out, which then also writes the JSON.
//
// Paths are anchored to this file, not to the working directory, so
// build-claim.sh / build-joinsplit.sh work from anywhere rather than only
// from the repo root.
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");

const argv = process.argv.slice(2);
let outPath = null;
let rsPath = null;
const positional = [];
for (let i = 0; i < argv.length; i++) {
  if (argv[i] === "--out") {
    outPath = argv[++i];
  } else if (argv[i] === "--rs") {
    rsPath = argv[++i];
  } else {
    positional.push(argv[i]);
  }
}

// claim circuit build uses claim_vk/claim_proof/claim_public;
// fall back to the benchmark names for backward compatibility.
const dir = path.join(ROOT, "circuits/build");
const circuit = positional[0] ?? null;
const vkFile = circuit
  ? `${circuit}_vk`
  : fs.existsSync(`${dir}/claim_vk.json`) ? "claim_vk" : "verification_key";
const proofFile = circuit
  ? `${circuit}_proof`
  : fs.existsSync(`${dir}/claim_proof.json`) ? "claim_proof" : "proof";
const pubFile = circuit
  ? `${circuit}_public`
  : fs.existsSync(`${dir}/claim_public.json`) ? "claim_public" : "public";
// Claim keeps its historical output names so build-claim.sh is unaffected.
const jsonOut = circuit ? `${dir}/${circuit}_soroban.json` : `${dir}/groth16_soroban.json`;
const rsOut = path.join(
  ROOT,
  circuit
    ? `contracts/zeekpay/src/${circuit}_fixture.rs`
    : "contracts/zeekpay/src/groth16_fixture.rs",
);
// groth16_fixture.rs is pinned at the 5-public-input shape ON PURPOSE. The
// deployed contract's derive_public_inputs pushes 5 Fr while claim.circom now
// has 7, and verifier::verify rejects the mismatch before any pairing math, so
// the staleness is safe rather than silently broken. Regenerating this file on
// its own does not fix anything, it just moves the mismatch: see the D1 -> D2
// handoff in pipeline/circom-circuit/changes.md, which lists the four changes
// that have to land together.
if (!outPath && !rsPath && !circuit && fs.existsSync(rsOut) && process.env.FORCE_FIXTURE !== "1") {
  console.error(`refusing to overwrite ${rsOut}`);
  console.error("");
  console.error("It is pinned at 5 public inputs deliberately. Regenerating it");
  console.error("alone moves the mismatch rather than fixing it. See the D1 -> D2");
  console.error("handoff in pipeline/circom-circuit/changes.md.");
  console.error("");
  console.error("If you are doing the coordinated contract + circuit change:");
  console.error("  FORCE_FIXTURE=1 node circuits/scripts/convert-to-soroban.mjs");
  process.exit(1);
}

const vk = JSON.parse(fs.readFileSync(`${dir}/${vkFile}.json`));
const proof = JSON.parse(fs.readFileSync(`${dir}/${proofFile}.json`));
const pub = JSON.parse(fs.readFileSync(`${dir}/${pubFile}.json`));

const be = (dec, bytes) => {
  const h = BigInt(dec).toString(16);
  if (h.length > bytes * 2) throw new Error(`overflow: ${dec}`);
  return h.padStart(bytes * 2, "0");
};
const g1 = (p) => be(p[0], 48) + be(p[1], 48);
const g2 = (p) => be(p[0][1], 48) + be(p[0][0], 48) + be(p[1][1], 48) + be(p[1][0], 48);
const fr = (d) => be(d, 32);

const out = {
  alpha1: g1(vk.vk_alpha_1),
  beta2: g2(vk.vk_beta_2),
  gamma2: g2(vk.vk_gamma_2),
  delta2: g2(vk.vk_delta_2),
  ic: vk.IC.map(g1),
  a: g1(proof.pi_a),
  b: g2(proof.pi_b),
  c: g1(proof.pi_c),
  pubs: pub.map(fr),
};
const DEFAULT_RS_HEADER = `// @generated by circuits/scripts/convert-to-soroban.mjs. DO NOT EDIT.
// Real Groth16/BLS12-381 proof from the local benchmark setup, encoded in
// Soroban bls12_381 byte layout. Public, throwaway-setup data (safe to commit).
`;

/** Rust constants for `out`, under `header`. */
function rustFixture(header) {
  const icArr = out.ic.map((h) => `    "${h}",`).join("\n");
  const pubArr = out.pubs.map((h) => `    "${h}",`).join("\n");
  return `${header}pub const ALPHA1: &str = "${out.alpha1}";
pub const BETA2: &str = "${out.beta2}";
pub const GAMMA2: &str = "${out.gamma2}";
pub const DELTA2: &str = "${out.delta2}";
pub const IC: &[&str] = &[
${icArr}
];
pub const PROOF_A: &str = "${out.a}";
pub const PROOF_B: &str = "${out.b}";
pub const PROOF_C: &str = "${out.c}";
pub const PUBS: &[&str] = &[
${pubArr}
];
`;
}

if (outPath) {
  fs.writeFileSync(outPath, JSON.stringify(out, null, 2));
  console.log(`wrote ${outPath} (--out: JSON only, no contract fixture written)`);
}
if (rsPath) {
  // Keep the target's own prose header. It says which proof the file freezes
  // and why, and replacing it with the generic banner would delete the only
  // record of that.
  let header = DEFAULT_RS_HEADER;
  if (fs.existsSync(rsPath)) {
    const existing = fs.readFileSync(rsPath, "utf8");
    const firstConst = existing.indexOf("pub const ");
    if (firstConst === -1) throw new Error(`${rsPath} has no "pub const " to replace`);
    header = existing.slice(0, firstConst);
  }
  fs.writeFileSync(rsPath, rustFixture(header));
  console.log(`wrote ${rsPath} (--rs)`);
}
if (!outPath && !rsPath) {
  fs.writeFileSync(jsonOut, JSON.stringify(out, null, 2));
  // Also emit a Rust fixture (tracked) for the verifier correctness test.
  fs.writeFileSync(rsOut, rustFixture(DEFAULT_RS_HEADER));
  console.log(`wrote ${jsonOut} + ${rsOut}`);
}
console.log("ic:", out.ic.length, "pubs:", out.pubs.length, "| G1 hex:", out.alpha1.length, "G2:", out.beta2.length, "Fr:", out.pubs[0].length);
